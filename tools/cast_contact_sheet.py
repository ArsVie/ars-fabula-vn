"""
cast_contact_sheet.py — Eval harness for the VN cast.

Generates a contact sheet showing every cast member's full expression set,
along with a sample scene-turn recording for review.

Usage:
    python tools/cast_contact_sheet.py [--curated] [--output report.md]

    --curated    Load curated sprites (default)
    --generated  Generate via ComfyUI (requires running ComfyUI)
    --output     Path to output report (default: cast_report.md)

The harness surfaces:
  1. Every expression sprite for every cast member (visual review)
  2. A sample scene turn with narration + expression change (timing review)
  3. Cast member identity consistency check (heuristic)

This is the "friend test" surface — a human judges whether it's show-worthy.
"""
from __future__ import annotations
import argparse
import os
import sys
from datetime import datetime

# Add project root to path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from vn_contracts import STANDARD_EXPRESSIONS, SceneState, cast_to_dict
from cast_pipeline import load_curated_cast, generate_cast


# ── Contact sheet builder ─────────────────────────────────────────────

def build_contact_sheet(cast: dict, output_path: str) -> str:
    """Build a markdown contact sheet for human review.

    Args:
        cast: dict[str, CastMember] — the full cast.
        output_path: Where to write the report.

    Returns:
        str: The report content.
    """
    lines = [
        "# Ars-Fabula VN — Cast Contact Sheet",
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"Cast size: {len(cast)} members",
        "",
        "---",
        "",
    ]

    # Section 1: Cast overview
    lines.append("## 🎭 Cast Overview")
    lines.append("")
    lines.append("| Character | Role | Voice | Expressions |")
    lines.append("|-----------|------|-------|-------------|")
    for name, member in sorted(cast.items()):
        char = member.character
        expr_count = len(member.expression_map)
        lines.append(
            f"| {char.name} | {char.role} | {char.voice_id} | {expr_count} |"
        )
    lines.append("")

    # Section 2: Expression sets per character
    lines.append("## 🎨 Expression Sets")
    lines.append("")
    for name, member in sorted(cast.items()):
        char = member.character
        lines.append(f"### {char.name} ({char.role})")
        lines.append("")
        lines.append(f"**Personality:** {char.personality}")
        lines.append(f"**Seed:** {char.seed}")
        lines.append(f"**Identity prompt:** `{char.identity_prompt[:80]}...`")
        lines.append("")

        # List each expression with file info
        lines.append("| Expression | Sprite Path | Size | Status |")
        lines.append("|------------|-------------|------|--------|")
        for expr in STANDARD_EXPRESSIONS:
            path = member.get_sprite(expr)
            if path and os.path.exists(path):
                size_bytes = os.path.getsize(path)
                lines.append(
                    f"| {expr} | `{os.path.relpath(path, os.path.dirname(output_path))}` "
                    f"| {size_bytes:,} bytes | ✅ |"
                )
            else:
                lines.append(f"| {expr} | — | — | ❌ Missing |")
        lines.append("")

        # Identity consistency check
        lines.append("#### Identity Check")
        lines.append("")
        neutral_path = member.get_sprite("neutral")
        hetero_count = 0
        for expr in STANDARD_EXPRESSIONS:
            if expr == "neutral":
                continue
            expr_path = member.get_sprite(expr)
            if expr_path and neutral_path and os.path.exists(expr_path) and os.path.exists(neutral_path):
                # Compare file sizes as a rough identity heuristic
                neutral_size = os.path.getsize(neutral_path)
                expr_size = os.path.getsize(expr_path)
                ratio = expr_size / max(neutral_size, 1)
                if 0.8 <= ratio <= 1.2:
                    hetero_count += 1

        consistency_pct = (hetero_count / max(len(STANDARD_EXPRESSIONS) - 1, 1)) * 100
        lines.append(
            f"- Expressions within plausible size range: {hetero_count}/{len(STANDARD_EXPRESSIONS) - 1} "
            f"({consistency_pct:.0f}%)"
        )
        lines.append(
            "  - *Size consistency is a rough proxy for identity preservation. "
            "Expressions significantly larger/smaller than neutral may indicate "
            "drift. Review visually for confirmation.*"
        )
        lines.append("")

    # Section 3: Sample scene turn
    lines.append("## 🎬 Sample Scene Turn")
    lines.append("")
    lines.append("The following is a sample scene turn generated by the mock engine:")
    lines.append("")

    # Run a quick engine test
    from model_client import MockModel
    from vn_engine import VNEngine

    # Build a mock model that returns plausible VN narration
    char_names = list(cast.keys())
    c1 = char_names[0] if len(char_names) > 0 else "Someone"
    
    def _mock_handler(messages, tools):
        return (
            f'[TOOL: advance_scene description="The afternoon sun filters through the classroom windows." background="classroom" mood="peaceful"]\n\n'
            f'[TOOL: set_expression character="{c1}" expression="smile"]\n\n'
            f'[{c1}]: "Hey, good to see you!"\n\n'
            f'The warmth of the moment settles around you like a familiar blanket.\n\n'
            f'[TOOL: offer_choices choices=\'[{{"id":"a","text":"Talk to {c1}"}},{{"id":"b","text":"Look out the window"}}]\']\n\n'
        )

    mock_model = MockModel(handler=_mock_handler)
    initial_scene = SceneState(cast=cast, present=list(cast.keys()),
                               background="classroom", mood="peaceful")
    engine = VNEngine(model=mock_model, cast=cast, scene=initial_scene)

    try:
        narration, scene = engine.run_turn("I look around the classroom")

        lines.append("```")
        lines.append(f"Turn: {scene.turn}")
        lines.append(f"Background: {scene.background}")
        lines.append(f"Mood: {scene.mood}")
        lines.append(f"Scene description: {scene.description[:200] if scene.description else '(none)'}")
        lines.append("")
        lines.append("Narration:")
        lines.append(narration[:500])
        lines.append("```")
    except Exception as e:
        lines.append(f"*Scene generation failed: {e}*")

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(
        "## 📋 Review Checklist\n\n"
        "- [ ] Every character's expression set looks consistent?\n"
        "- [ ] No identity drift across expressions?\n"
        "- [ ] Expression changes timed well in the sample scene?\n"
        "- [ ] The scene turn feels alive?\n"
        "- [ ] Would you show this to a friend?\n"
    )

    report = "\n".join(lines)

    with open(output_path, "w") as f:
        f.write(report)

    print(f"\n📋 Contact sheet written to: {output_path}")
    print(f"   {len(cast)} characters, {sum(len(m.expression_map) for m in cast.values())} total sprites")
    return report


# ═══════════════════════════════════════════════════════════════════════
# Main
# ═══════════════════════════════════════════════════════════════════════

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="VN Cast Contact Sheet")
    parser.add_argument("--curated", action="store_true", default=True,
                        help="Load curated sprites (default)")
    parser.add_argument("--generated", action="store_true",
                        help="Generate via ComfyUI (requires server)")
    parser.add_argument("--output", default="cast_report.md",
                        help="Output report path")
    args = parser.parse_args()

    if args.generated:
        print("Generating cast via ComfyUI...")
        cast = cast_to_dict(generate_cast({"preset": "full_cast"}))
    else:
        print("Loading curated cast...")
        cast = cast_to_dict(load_curated_cast())

    if not cast:
        print("ERROR: No cast loaded!")
        sys.exit(1)

    build_contact_sheet(cast, args.output)
